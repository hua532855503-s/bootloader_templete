void UART2_RX_PtrInit(void)
{
  /* 清空接收缓冲区并将读指针归零。 */
  uart_rx_read_pos = 0;
  memset(UART2_RX_BUF, 0, UART_RX_SIZE);
}

uint16_t UART2_RX_Read(uint8_t *data, uint16_t max_len)
{
  uint16_t write_pos;
  uint16_t count = 0;

  /* DMA 计数器递减，因此用缓冲区总长度减去剩余数得到写指针。 */
  write_pos = UART_RX_SIZE - __HAL_DMA_GET_COUNTER(&hdma_usart2_rx);

  /* 读取 DMA 已写入但应用尚未处理的数据，支持环形回绕。 */
  while (uart_rx_read_pos != write_pos && count < max_len)
  {
    data[count++] = UART2_RX_BUF[uart_rx_read_pos];

    uart_rx_read_pos++;
    if (uart_rx_read_pos >= UART_RX_SIZE)
    {
      uart_rx_read_pos = 0;
    }
  }

  return count;
}

/* 通过 USART2 阻塞发送以 '\0' 结尾的字符串。 */
void UART2_SendString(const char *str)
{
  uint16_t len = 0;

  while (str[len] != '\0')
  {
    len++;
  }

  if (HAL_UART_Transmit(&huart2, (uint8_t *)str, len, 1000) != HAL_OK)
  {
    Error_Handler();
  }
}

/* 将无符号 32 位整数转换为十进制文本并通过 USART2 发送。 */
void UART2_SendU32(uint32_t value)
{
  char buffer[10];
  uint8_t index = sizeof(buffer);

  do
  {
    buffer[--index] = (char)('0' + value % 10U);
    value /= 10U;
  } while (value != 0U);

  if (HAL_UART_Transmit(&huart2, (uint8_t *)&buffer[index], sizeof(buffer) - index, 1000) != HAL_OK)
  {
    Error_Handler();
  }
}

